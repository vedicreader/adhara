"Write src/tables.rs: the transliteration dicts of litesearch's sanskrit.py and apsw's Extended_Pictographic ranges."
import litesearch.sanskrit as s, apsw.unicode as u
from pathlib import Path

def tbl(name, d):
    "One Rust match fn for a char -> str dict; multi-char keys are skipped, since deva2ascii looks up one char at a time."
    arms = '\n'.join(f"        '\\u{{{ord(k):x}}}' => \"{v}\"," for k, v in d.items() if len(k) == 1)
    return f"pub fn {name}(c: char) -> Option<&'static str> {{\n    Some(match c {{\n{arms}\n        _ => return None,\n    }})\n}}\n\n"

def ranges(f):
    "Inclusive (lo, hi) code point ranges where `f` holds."
    out, lo = [], None
    for c in range(0x110000):
        ok = not 0xd800 <= c <= 0xdfff and f(chr(c))
        if ok and lo is None: lo = c
        if not ok and lo is not None: out.append((lo, c - 1)); lo = None
    return out

rs = ranges(u.is_extended_pictographic)
ext = (f"/// Extended_Pictographic, Unicode {u.unicode_version}, from apsw.\npub const EXT_PICT: [(u32, u32); {len(rs)}] = [\n"
       + ''.join(f"    (0x{a:x}, 0x{b:x}),\n" for a, b in rs) + "];\n\n"
       + "pub fn ext_pict(c: char) -> bool {\n    let c = c as u32;\n    EXT_PICT.binary_search_by(|&(a, b)| if b < c { std::cmp::Ordering::Less } else if a > c { std::cmp::Ordering::Greater } else { std::cmp::Ordering::Equal }).is_ok()\n}\n")
hdr = '// Generated by scripts/gen_tables.py from litesearch/sanskrit.py and apsw.unicode; do not edit.\n\n'
body = ''.join(tbl(n, getattr(s, '_' + n.upper())) for n in ['indep', 'cons', 'matra', 'sign'])
Path(__file__).parent.parent.joinpath('src/tables.rs').write_text(hdr + body + ext)
